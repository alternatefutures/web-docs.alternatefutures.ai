#!/usr/bin/env node
/**
 * Generate the CLI command reference (content/docs/cli/commands.mdx) by
 * statically parsing the acc CLI source (Commander registrations).
 *
 * The parser lives in scripts/lib/cli-model.mjs and is shared with
 * scripts/check-cli-drift.mjs, so the reference and the lint always agree on
 * which commands and flags exist. See that file for how the CLI repo is found.
 */
import { writeFileSync } from 'fs';
import { dirname, join, resolve } from 'path';
import { fileURLToPath } from 'url';
import { GROUPS, ROOT_COMMANDS, displayOf, loadCliModel } from './lib/cli-model.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(__dirname, '..');
const OUTPUT = join(REPO_ROOT, 'content/docs/cli/commands.mdx');

let model;
try {
  model = loadCliModel({ repoRoot: REPO_ROOT });
} catch (err) {
  console.error(`❌ ${err.message}`);
  process.exit(1);
}
const { cliRepo, pkg, root } = model;

// MDX-safe: escape chars that would be parsed as JSX/expressions.
const mdx = (s) =>
  String(s ?? '')
    .replace(/\{/g, '\\{')
    .replace(/</g, '\\<');

// Inside inline code spans MDX needs no escaping, but table pipes do.
const code = (s) => `\`${String(s ?? '').replace(/\|/g, '\\|')}\``;

let out = `---
title: "Command reference"
description: "Complete reference for every acc command and flag, generated from the CLI source."
---

{/* AUTO-GENERATED by scripts/generate-cli-docs.mjs from ${pkg.name}@${pkg.version} — do not edit by hand. */}

<Callout type="info">
Use \`acc <command> --help\` to see detailed help for any command. This page is
auto-generated from the CLI source (v${pkg.version}).
</Callout>

## Global options

- \`--debug\` · enable debug output
- \`--local\` · use local dev services (separate credential slot)
- \`-V, --version\` · print CLI version
- \`-h, --help\` · help for any command

`;

function renderCommand(node) {
  let s = `### ${code(displayOf(node))}\n\n`;
  if (node.description) s += `${mdx(node.description)}\n\n`;
  if (node.options.length > 0) {
    s += '| Option | Description |\n|--------|-------------|\n';
    for (const opt of node.options) {
      const def = opt.defaultValue ? ` (default: ${code(opt.defaultValue)})` : '';
      const desc = mdx(opt.description).replace(/\|/g, '\\|').replace(/`/g, '');
      s += `| ${code(opt.flag)} | ${desc}${def} |\n`;
    }
    s += '\n';
  }
  return s;
}

// A command followed by its subcommands, depth first, in registration order.
function renderTree(node, seen) {
  let s = '';
  const key = displayOf(node);
  if (!seen.has(key)) {
    seen.add(key);
    s += renderCommand(node);
  }
  for (const child of node.children) s += renderTree(child, seen);
  return s;
}

const seen = new Set();
const includeUnreleased = process.env.DOCS_INCLUDE_UNRELEASED_SURFACES === '1';
for (const group of GROUPS) {
  if (group.unreleased && !includeUnreleased) continue;
  out += `## ${group.title}\n\n`;
  if (group.title === 'Account') {
    for (const cmd of root.children.filter((c) => ROOT_COMMANDS.includes(c.name))) {
      out += renderTree(cmd, seen);
    }
  }
  for (const dir of group.dirs) {
    const node = root.children.find((c) => c.name === dir);
    if (!node) continue;
    out += renderTree(node, seen);
  }
}

out += `
## Environment variables

| Variable | Purpose |
|----------|---------|
| \`AF_TOKEN\` | Personal access token (overrides stored login, for CI/agents) |
| \`AF_PROJECT_ID\` | Project to operate on (for CI/agents) |
| \`AF_ORG_ID\` | Organization override |
| \`AF_API_URL\` | Override cloud API base URL |
| \`AF_AUTH_API_URL\` | Override auth service URL |
`;

// A root command that belongs to no group would vanish from the page silently
// (that is how the swarm commands were missed on 2026-09-11). Warn so the
// GROUPS table in lib/cli-model.mjs gets the new name.
const grouped = new Set([...ROOT_COMMANDS, ...GROUPS.flatMap((g) => g.dirs)]);
const ungrouped = root.children.map((c) => c.name).filter((n) => !grouped.has(n) && !['help', 'version'].includes(n));
if (ungrouped.length > 0) console.warn(`⚠️  ${ungrouped.length} root command(s) in no GROUPS entry (not documented): ${ungrouped.join(', ')}`);
writeFileSync(OUTPUT, out, 'utf8');
console.log(`✨ Wrote ${OUTPUT} from ${cliRepo} (${pkg.name}@${pkg.version}, ${model.commands.length} commands)`);
